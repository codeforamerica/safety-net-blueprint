#!/usr/bin/env node
/**
 * Builds dist/browser.js — a self-contained IIFE bundle of the rules evaluator
 * for use in browser environments.
 *
 * Uses esbuild to bundle src/evaluator.js and its dependencies (including
 * @bufbuild/cel) into a single file. Only { evaluate } is exposed. The
 * notices of the third-party code inside it go at the end.
 *
 * Exposed as: window.RulesEngine = { evaluate }
 *
 * Usage: node scripts/build-browser.js
 */

import { build } from 'esbuild';
import { mkdirSync, writeFileSync, unlinkSync } from 'fs';
import { bundledPackages, noticeProblems, noticesComment } from '../../../scripts/third-party-notices.js';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const distDir = resolve(rootDir, 'dist');

/**
 * @param {string} [outfile]
 * @returns {Promise<{ outfile: string, packages: ReturnType<typeof bundledPackages> }>}
 */
export async function buildBrowser(outfile = resolve(distDir, 'browser.js')) {
  mkdirSync(distDir, { recursive: true });
  mkdirSync(dirname(outfile), { recursive: true });

  // Temporary entry point that exposes only the public API
  const entryPath = resolve(distDir, `_entry-${process.pid}.js`);
  writeFileSync(entryPath, `
import { evaluate } from '../src/evaluator.js';
window.RulesEngine = { evaluate };
`);

  try {
    const { metafile, outputFiles } = await build({
      entryPoints: [entryPath],
      absWorkingDir: rootDir,
      bundle: true,
      format: 'iife',
      minify: true,
      metafile: true,
      write: false,
      outfile,
      banner: {
        js: `/**
 * @codeforamerica/blueprint-rules-engine — browser bundle
 * Exposes: window.RulesEngine = { evaluate }
 * Third-party notices are at the end of this file.
 *
 * Generated by scripts/build-browser.js. Do not edit directly.
 */`,
      },
    });
    const packages = bundledPackages(metafile, rootDir);
    writeFileSync(outfile, outputFiles[0].text + noticesComment(packages));
    return { outfile, packages };
  } finally {
    unlinkSync(entryPath);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { outfile, packages } = await buildBrowser();
  console.log(`Wrote ${outfile}, with the notices of ${packages.length} third-party packages.`);
  // Not a failure: this runs on every install. tests/browser-bundle.test.js fails on it.
  for (const line of noticeProblems(packages)) console.warn(`Warning: ${line}`);
}
