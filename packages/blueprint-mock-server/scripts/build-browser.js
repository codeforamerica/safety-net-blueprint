#!/usr/bin/env node
/**
 * Builds dist/blueprint-mock-server.esm-browser.js: the mock server's browser
 * entry, bundled with its dependencies into one ES module, with the notices of
 * the third-party code inside it at the end, for a page that has no bundler.
 * It's named for the package, the format and where it runs, as Vue names its
 * builds, so the name still says what it is once it's copied next to a page;
 * a classic-script build would sit beside it as blueprint-mock-server.global.js.
 *
 * Run by npm on install and before publishing, as the rules engine's bundle
 * is, and not committed: a committed copy would be whatever the last person to
 * rebuild it had.
 *
 * Usage: node scripts/build-browser.js [--out=<file>]
 */

import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundledPackages, noticeProblems, noticesComment } from '../../../scripts/third-party-notices.js';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * @param {string} outfile
 * @returns {Promise<{ outfile: string, packages: ReturnType<typeof bundledPackages> }>}
 */
export async function buildBrowser(outfile = resolve(rootDir, 'dist/blueprint-mock-server.esm-browser.js')) {
  const { metafile, outputFiles } = await build({
    entryPoints: [resolve(rootDir, 'src/browser.js')],
    absWorkingDir: rootDir,
    bundle: true,
    platform: 'browser',
    format: 'esm',
    minify: true,
    metafile: true,
    write: false,
    outfile,
    logLevel: 'error',
    banner: {
      js: `/**
 * @codeforamerica/blueprint-mock-server — browser bundle
 * Exports what @codeforamerica/blueprint-mock-server/browser does, with nothing
 * else to install.
 * Third-party notices are at the end of this file.
 *
 * Generated by scripts/build-browser.js. Do not edit directly.
 */`,
    },
  });
  const packages = bundledPackages(metafile, rootDir);
  mkdirSync(dirname(outfile), { recursive: true });
  writeFileSync(outfile, outputFiles[0].text + noticesComment(packages));
  return { outfile, packages };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = process.argv.slice(2).find((arg) => arg.startsWith('--out='))?.slice('--out='.length);
  const { outfile, packages } = await buildBrowser(out ? resolve(out) : undefined);
  console.log(`Wrote ${outfile}, with the notices of ${packages.length} third-party packages.`);
  // Not a failure: this runs on every install. The bundle's tests fail on it.
  for (const line of noticeProblems(packages)) console.warn(`Warning: ${line}`);
}
